source("C:/Users/masse/Desktop/KefiR/KefiR-mbay/dev/mbay/scripts/agent_load_bay.R"); .kefir_bay()
suppressMessages(library(BayesFactor))
set.seed(4)
d3 <- expand.grid(A = c("a1", "a2"), B = c("b1", "b2"), C = c("c1", "c2", "c3"), r = 1:4)
d3$y <- rnorm(nrow(d3), (d3$A == "a2") * (d3$B == "b2") * 1.5)

cat("== which models have large error, seed 1 ==\n")
r <- m.bay(y ~ A * B * C, data = d3, verbose = FALSE, sensitivity = TRUE, seed = 1)
# errors per r column are not stored in the output; recompute directly
sp <- .bay_fact_space(c("A", "B", "C", "A:B", "A:C", "B:C", "A:B:C"))
inp <- .bay_parse_input(formula = y ~ A * B * C, data = d3)
bf <- .bay_fact_logbf(inp$response, inp$factors, sp, c(0.25, 0.5, 1), 10000L, 1L)
print(data.frame(model = r$models$model, round(bf$log_bf, 3), err = round(100 * bf$error, 1)))
cat("error_pct reported:", r$effects$error_pct[1], " max over all r:", 100 * max(bf$error), "\n")
cat("notes:", r$notes$en, "\n")
cat("sens verdicts:", r$sensitivity$verdict_terms, " global:", r$sensitivity$verdict, "\n")
cat("== reference anovaBF 1e5 iterations on hereditary models ==\n")
set.seed(1)
ab <- anovaBF(y ~ A * B * C, data = d3, whichModels = "all", rscaleFixed = 0.5, iterations = 1e5, progress = FALSE)
x <- extractBF(ab, logbf = TRUE)
key <- function(s) vapply(strsplit(s, " + ", fixed = TRUE), function(v) paste(sort(v), collapse = "+"), "")
mk <- key(r$models$model[-1])
m <- match(mk, key(rownames(x)))
cmp <- data.frame(model = r$models$model[-1], kefir = r$models$log_bf[-1], ref = x$bf[m], ref_err = 100 * x$error[m])
cmp$diff <- cmp$kefir - cmp$ref
print(cmp, digits = 3)
lb_ref <- c(0, x$bf[m])
inc_ref <- .bay_fact_terms(sp, lb_ref, .bay_fact_prior(sp, "hop"))
print(data.frame(term = inc_ref$term, ref = round(inc_ref$p_h1, 3)))

