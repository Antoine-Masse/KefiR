cat("### Cas G : rendement selon l'engrais, a surface egale (3 engrais, 15 parcelles), pentes paralleles\n> m.bay(rendement ~ engrais + surface, data = d)\n\n")
set.seed(31)
d <- data.frame(engrais = factor(rep(c("E1", "E2", "E3"), each = 15)), surface = runif(45, 5, 15))
d$rendement <- 20 + 1.5 * d$surface + c(0, 0, 3)[d$engrais] + rnorm(45, 0, 2)
invisible(m.bay(rendement ~ engrais + surface, data = d))
cat("\n### Cas H : score selon la methode, avec la note d'entree, pentes differentes (methode * note)\n> m.bay(score ~ methode * note, data = d)\n\n")
set.seed(32)
d <- data.frame(methode = factor(rep(c("classique", "projet"), each = 25)), note = runif(50, 6, 18))
d$score <- 5 + 0.6 * d$note + (d$methode == "projet") * (0.5 * (d$note - 12)) + rnorm(50, 0, 1.5)
invisible(m.bay(score ~ methode * note, data = d))
cat("\n### Cas I : poids selon le regime, avec l'age, groupes qui se recouvrent peu sur l'age\n> m.bay(poids ~ regime + age, data = d, sensitivity = FALSE)\n\n")
set.seed(33)
d <- data.frame(regime = factor(rep(c("R1", "R2"), each = 15)), age = c(runif(15, 20, 35), runif(15, 32, 50)))
d$poids <- 60 + 0.4 * d$age + 2 * (d$regime == "R2") + rnorm(30, 0, 3)
invisible(m.bay(poids ~ regime + age, data = d, sensitivity = FALSE))
