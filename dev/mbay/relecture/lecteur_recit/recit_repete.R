cat("### Cas D : tension avant / apres traitement, 14 patients (une mesure manquante)\n> m.bay(tension ~ moment | patient, data = d)\n\n")
set.seed(21)
d <- data.frame(patient = factor(rep(1:14, 2)), moment = factor(rep(c("avant", "apres"), each = 14), levels = c("avant", "apres")))
d$tension <- 140 + rnorm(14, 0, 12)[d$patient] - 6 * (d$moment == "apres") + rnorm(28, 0, 5)
d <- d[-3, ]
invisible(m.bay(tension ~ moment | patient, data = d))
cat("\n### Cas E : temps de reaction a 4 sessions, 12 sujets\n> m.bay(rt ~ session | sujet, data = d)\n\n")
set.seed(22)
d <- data.frame(sujet = factor(rep(1:12, 4)), session = factor(rep(paste0("S", 1:4), each = 12)))
d$rt <- 450 + rnorm(12, 0, 40)[d$sujet] + c(0, -5, -25, -30)[d$session] + rnorm(48, 0, 15)
invisible(m.bay(rt ~ session | sujet, data = d))
cat("\n### Cas F : score selon le groupe (entre sujets) et la seance (intra), 2 x 3, 10 sujets par groupe\n> m.bay(score ~ groupe * seance + Error(id / seance), data = d)\n\n")
set.seed(23)
d <- expand.grid(id = factor(1:20), seance = factor(c("s1", "s2", "s3")))
d$groupe <- factor(ifelse(as.integer(d$id) <= 10, "temoin", "entraine"))
d$score <- 50 + rnorm(20, 0, 6)[d$id] + 4 * (d$seance != "s1") * (d$groupe == "entraine") + rnorm(nrow(d), 0, 3)
invisible(m.bay(score ~ groupe * seance + Error(id / seance), data = d))
