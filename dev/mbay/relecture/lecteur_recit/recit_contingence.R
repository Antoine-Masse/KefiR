cat("### Cas J : germination (oui/non) selon le traitement des graines, 3 traitements, 30 graines chacun\n> m.bay(germe ~ traitement, data = d)\n\n")
set.seed(41)
d <- data.frame(traitement = factor(rep(c("temoin", "froid", "chaud"), each = 30), levels = c("temoin", "froid", "chaud")))
d$germe <- factor(ifelse(rbinom(90, 1, c(.5, .5, .8)[d$traitement]) == 1, "oui", "non"), levels = c("non", "oui"))
invisible(m.bay(germe ~ traitement, data = d))
cat("\n### Cas K : reussite (0/1) selon le groupe de TD, 2 groupes, 18 etudiants chacun\n> m.bay(reussite ~ groupe, data = d)\n\n")
set.seed(42)
d <- data.frame(groupe = factor(rep(c("TD1", "TD2"), each = 18)))
d$reussite <- rbinom(36, 1, c(.6, .7)[d$groupe])
invisible(m.bay(reussite ~ groupe, data = d))
cat("\n### Cas L : couleur des fleurs (3 couleurs) selon la parcelle, 2 parcelles\n> m.bay(couleur ~ parcelle, data = d)\n\n")
set.seed(43)
d <- data.frame(parcelle = factor(rep(c("P1", "P2"), each = 40)))
d$couleur <- factor(c(sample(c("blanc", "rose", "rouge"), 40, TRUE, c(.5, .3, .2)), sample(c("blanc", "rose", "rouge"), 40, TRUE, c(.2, .3, .5))))
invisible(m.bay(couleur ~ parcelle, data = d))
