try_ <- function(lbl, expr) {
  w <- character(0)
  r <- tryCatch(withCallingHandlers(expr, warning = function(c) {w <<- c(w, conditionMessage(c)); invokeRestart("muffleWarning")}),
    error = function(e) paste("ERREUR:", conditionMessage(e)))
  if (is.list(r)) r <- c(log_bf = r$log_bf, err = r$error_pct, ess = r$ess, n = r$n_draws)
  cat(sprintf("%-52s %s", lbl, paste(format(r, digits = 6), collapse = " ")), if (length(w)) paste0(" [W: ", paste(unique(w), collapse = " | "), "]"), "\n")
}
