tm <- function(lab,expr,lim=150) { t0<-Sys.time(); setTimeLimit(elapsed=lim,transient=TRUE)
  r <- tryCatch(expr,error=function(e) {cat(lab,": ERREUR",substr(conditionMessage(e),1,90),"\n");NULL}); setTimeLimit()
  el<-as.numeric(difftime(Sys.time(),t0,units="secs"))
  if(!is.null(r)) cat(sprintf("%s [%.0fs] P=%.4f err=%.2f%% lois=%s notes=%s\n",lab,el,r$prob_effect,r$effects$error_pct,paste(sprintf("%s=%.3f",r$laws$law,r$laws$posterior),collapse=" "),paste(r$notes$fr,collapse=" / "))) else cat(sprintf("  arret apres %.0fs\n",el)); flush.console() }
