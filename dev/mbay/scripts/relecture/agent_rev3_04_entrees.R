go <- function(lab,expr) { e<-substitute(expr)
  r <- tryCatch(withCallingHandlers(eval(e,parent.frame()),warning=function(w){cat("  [warning]",conditionMessage(w),"\n");invokeRestart("muffleWarning")}),error=function(err) structure(conditionMessage(err),class="ERR"))
  if (inherits(r,"ERR")) cat(sprintf("%-40s ERREUR: %s\n",lab,substr(unclass(r),1,110))) else cat(sprintf("%-40s plan=%s n=%s label=%s P=%.3f notes=%s\n",lab,r$plan,r$n,r$label,r$prob_effect,paste(r$notes$fr,collapse=" / ")))
  flush.console()
}
