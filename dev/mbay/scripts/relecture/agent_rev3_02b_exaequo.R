try1 <- function(lab, ...) {
  t0 <- Sys.time(); setTimeLimit(elapsed=100,transient=TRUE)
  a <- tryCatch(ans_of(...), error=function(e) {cat(lab,"ERREUR:",substr(conditionMessage(e),1,80),"\n");NULL})
  setTimeLimit()
  if (!is.null(a)) show(sprintf("%s [%.0fs]",lab,as.numeric(difftime(Sys.time(),t0,units="secs"))),a)
  flush.console(); invisible(a)
}
