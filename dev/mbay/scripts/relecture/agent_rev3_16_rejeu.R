source("C:/Users/masse/Desktop/KefiR/KefiR-mbay/dev/mbay/scripts/relecture/agent_rev3_lib.R")
set.seed(1)
d <- data.frame(id=rep(1:15,2), temps=rep(c("t1","t2"),each=15), dose=rep(c(1,2,5),10), stringsAsFactors=FALSE)
d$y <- rep(rnorm(15,0,3),2)+(d$temps=="t2")*.8+rnorm(30,0,.3)
q <- function(...) m.bay(...,verbose=FALSE,draws=500L,sensitivity=FALSE)
go <- function(lab,expr) { r <- tryCatch(expr,error=function(e) {cat(lab,": ERREUR",substr(conditionMessage(e),1,100),"\n");NULL})
  if(!is.null(r)) cat(sprintf("%s : plan=%s P=%.3f groupes=%s (%s) label=%s\n",lab,r$plan,r$prob_effect,paste(r$descriptive_stats$group,collapse="/"),paste(r$descriptive_stats$n,collapse=","),r$label)); flush.console() }
go("y~temps, wt='temps' sans id",q(y~temps,data=d,wt="temps"))
go("y~temps, within='temps' sans id",q(y~temps,data=d,within="temps"))
go("y~temps, id='id'",q(y~temps,data=d,id="id"))
cat("t.test apparie p =",t.test(d$y[d$temps=="t2"],d$y[d$temps=="t1"],paired=TRUE)$p.value,"; non apparie p =",t.test(y~temps,d)$p.value,"\n")
go("y~I(dose>2)",q(y~I(dose>2),data=d))
go("y~ifelse(dose>2,'a','b')",q(y~ifelse(dose>2,'a','b'),data=d))
go("y~dose",q(y~dose,data=d))
go("g longueur 15 pour y 30",q(d$y,rep(c("a","b"),length.out=15)))
go("g NaN/Inf",q(c(d$y,1,2),c(d$dose,NaN,Inf)))
go("y avec 1e200",q(c(d$y[-1],1e200),d$temps))
go("y*1e-200",q(d$y*1e-200,d$temps))
go("draws=1",m.bay(d$y,d$temps,verbose=FALSE,draws=1L,sensitivity=FALSE))
go("u=1e-5",q(d$y,d$temps,u=1e-5))
go("y~temps, temps hors data",{e<-d["y"];temps<-d$temps;q(y~temps,data=e)})
cat("--- prior_h1=.2 : cotes reelles et annoncees\n")
set.seed(9); y<-c(rnorm(20),rnorm(20,1)); g<-rep(1:2,each=20)
r <- m.bay(y,g,draws=300L,prior_h1=.2,verbose=FALSE); print(colnames(r$sensitivity$grid)); o <- capture.output(print(r)); cat(grep("Vari|Varied",o,value=TRUE),"\n")
cat("--- laws='normal_eq' : priors annonces\n")
r <- m.bay(y,g,laws="normal_eq",draws=300L,verbose=FALSE); o <- capture.output(print(r)); cat(grep("Bruit|Noise|Vari",o,value=TRUE),sep="\n")
cat("--- temps defaut, k=2 n=20 ; k=8 n=10 (draws=4000, sensibilite)\n")
t0<-Sys.time(); r<-m.bay(y,g,verbose=FALSE); cat(format(Sys.time()-t0),"\n")
set.seed(7); y8 <- c(rnorm(70), rnorm(3,1000,1)); g8 <- rep(1:8,c(rep(10,7),3))
t0<-Sys.time(); r<-m.bay(y8,g8,verbose=TRUE); cat(format(Sys.time()-t0),"\n"); print(r$sensitivity$by_law)
set.seed(7); y6 <- c(rnorm(50), rnorm(3,1000,1)); g6 <- rep(1:6,c(rep(10,5),3))
r<-m.bay(y6,g6,draws=1000L,verbose=FALSE,sensitivity=FALSE); cat("k=6 n_s=3 d=1000 : P=",r$prob_effect," Welch p=",oneway.test(y6~factor(g6))$p.value," note ? ",any(grepl("Many",r$notes$en)),"\n")
