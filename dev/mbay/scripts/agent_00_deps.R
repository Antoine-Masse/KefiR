cat("g++:", Sys.which("g++"), " make:", Sys.which("make"), "\nRTOOLS env:", Sys.getenv("RTOOLS45_HOME"), Sys.getenv("RTOOLS46_HOME"), Sys.getenv("RTOOLS44_HOME"), "\n")
cat("pkgbuild installe:", requireNamespace("pkgbuild", quietly=TRUE), "\n")
if (requireNamespace("pkgbuild", quietly=TRUE)) print(tryCatch(pkgbuild::has_build_tools(debug=FALSE), error=function(e) conditionMessage(e)))
print(list.files("C:/", pattern="(?i)rtools"))
bin <- available.packages(type="win.binary")
src <- available.packages(type="source")
cat("contrib url:", contrib.url("https://cloud.r-project.org", type="win.binary"), "  n bin:", nrow(bin), " n src:", nrow(src), "\n")
cands <- c("BayesFactor","bayestestR","BAS","rstanarm","brms","bridgesampling","rstan","StanHeaders")
tab <- data.frame(pkg=cands, bin=bin[match(cands,rownames(bin)),"Version"], src=src[match(cands,rownames(src)),"Version"])
print(tab)
desc <- read.dcf("C:/Users/masse/Desktop/KefiR/KefiR-mbay/DESCRIPTION")
imp <- trimws(gsub("[(].*[)]","",strsplit(desc[,"Imports"],",")[[1]]))
ip <- rownames(installed.packages(priority="base"))
kdeps <- unique(c(imp, unlist(tools::package_dependencies(imp, db=bin, which=c("Depends","Imports","LinkingTo"), recursive=TRUE))))
kdeps_nb <- setdiff(kdeps, ip)
cat("Imports KefiR:", length(imp), " ; fermeture recursive hors base:", length(kdeps_nb), "\n")
inst <- rownames(installed.packages())
res <- list()
for (p in c("BayesFactor","bayestestR","BAS","rstanarm","brms","bridgesampling")) {
  d <- unique(unlist(tools::package_dependencies(p, db=bin, which=c("Depends","Imports","LinkingTo"), recursive=TRUE)))
  d <- setdiff(d, ip)
  ex <- setdiff(d, kdeps_nb)
  res[[p]] <- data.frame(pkg=p, recursives=length(d), au_dela_KefiR=length(ex), deja_installes=sum(ex %in% inst))
  cat("\n==",p,": rec",length(d)," au-dela KefiR",length(ex),"\n", paste(ex,collapse=" "),"\n")
}
print(do.call(rbind,res))
all_ex <- setdiff(unique(unlist(tools::package_dependencies(c("BayesFactor","bayestestR","BAS","rstanarm","brms","bridgesampling"),db=bin,which=c("Depends","Imports","LinkingTo"),recursive=TRUE))),c(ip,kdeps_nb))
cat("\nunion au-dela KefiR:",length(all_ex),"\n")
# Absents en binaire ?
need <- unique(c(cands, all_ex))
cat("sans binaire:", paste(setdiff(need, rownames(bin)),collapse=" "), "\n")
b <- need[need %in% rownames(bin) & need %in% rownames(src)]
print(b[bin[b,"Version"]!=src[b,"Version"]])
